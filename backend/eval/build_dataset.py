def main() -> None:
    out = Path(__file__).with_name("dataset.jsonl")
    with out.open("w", encoding="utf-8") as f:
        for i, (text, lang, cat, extra) in enumerate(ROWS, start=1):
            row = {
                "id": f"ev{i:03d}",
                "text": text,
                "language": lang,
                "category": cat,
                "departments": sorted(extra.get("departments", [DEPT[cat]])),
                "allow_extra": extra.get("allow_extra", []),
                "tags": extra.get("tags", []),
            }
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"wrote {len(ROWS)} rows to {out}")


if __name__ == "__main__":
    main()
